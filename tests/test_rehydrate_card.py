    def _past_the_last_step(self, records, pad=4000, ensure_ascii=True):
        filler = _user(
            [{"type": "tool_result", "content": "x" * pad}],
            timestamp="2026-11-05T12:00:00.000Z",
            toolUseResult={"stdout": "tool output that must not be quoted"},
        )
        path = self.write_transcript(list(records) + [filler], ensure_ascii=ensure_ascii)
        size = os.path.getsize(path)
        last = size // 2
        self.assertGreater(last, 64)
        self.assertGreater(size, last)
        return path, (max(1, last // 2), last)

    def test_last_typed_reads_past_the_last_step(self):
        # source: when every tail step misses, the whole file supplies the last typed words
        prompt = "Keep this prompt past the tail."
        path, steps = self._past_the_last_step([
            _user(prompt, timestamp="2026-11-05T09:00:00.000Z"),
            _user(
                "This tool row must not count.",
                timestamp="2026-11-05T10:30:00.000Z",
                toolUseResult={"stdout": "nope"},
            ),
        ])
        raw = Path(path).read_bytes()
        self.assertNotIn(prompt.encode("utf-8"), raw[-steps[-1]:])
        with patch.object(rehydrate, "LAST_TYPED_STEPS", steps):
            self.assertEqual(rehydrate.last_typed(path), {
                "text": prompt, "ts": "2026-11-05T09:00:00.000Z",
            })
            card = rehydrate.build_card("s1", path)
        self.assertIn(prompt, card)
        self.assertNotIn("none found", card)
        self.assertNotIn("This tool row must not count.", card)

