def _user(content, timestamp="2026-11-05T10:00:00.000Z", **extra):
    record = {
        "type": "user",
        "timestamp": timestamp,
        "message": {"role": "user", "content": content},
    }
    record.update(extra)
    return record


def _queued(prompt, origin, mode="prompt", timestamp="2026-11-05T10:05:00.000Z"):
    return {
        "type": "attachment",
        "timestamp": timestamp,
        "attachment": {
            "type": "queued_command",
            "prompt": prompt,
            "commandMode": mode,
            "origin": {"kind": origin},
            "timestamp": timestamp,
        },
    }


OPUS = "claude-opus-5-5"
HAIKU = "claude-haiku-5-5"
SONNET = "claude-sonnet-5-5"
FABLE = "claude-fable-5-1"


def _reply(model, timestamp="2026-11-05T10:01:00.000Z", **extra):
    record = {
        "type": "assistant",
        "timestamp": timestamp,
        "message": {
            "role": "assistant",
            "model": model,
            "content": [{"type": "text", "text": "Working."}],
        },
    }
    record.update(extra)
    return record


def _model_attachment(model, timestamp="2026-11-05T09:59:00.000Z"):
    return {
        "type": "attachment",
        "isSidechain": False,
        "timestamp": timestamp,
        "attachment": {
            "type": "model",
            "identity": {"modelId": model, "marketingName": "Model"},
            "text": "You are powered by the model.",
        },
    }


def _model_command(name):
    return _user(
        "<command-name>" + name + "</command-name>\n"
        "<command-message>" + name.lstrip("/") + "</command-message>\n"
        "<command-args></command-args>",
        timestamp="2026-11-05T10:02:00.000Z",
    )


