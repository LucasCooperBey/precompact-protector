        count.assert_not_called()
        self.assertEqual(len(self.logs), 1)
        self.assertIn("rehydrate: helper compaction for s1", self.logs[0])
        self.assertIn("compaction=none", self.logs[0])
        self.assertIn("owner=helper", self.logs[0])
        self.assertIn("model=claude-haiku-5-5", self.logs[0])
        self.assertIn("prompt=p1", self.logs[0])

